"""Чистые функции расчёта премий (BACKLOG T-3).

Модуль не зависит от Flet и БД — формула вынесена из
``PremiaWorkPage.show_results_click`` без изменения значений, чтобы её
можно было покрыть табличными тестами (tests/test_points_premia.py).

Приоритет оснований (сверху вниз):
  1. несданные предметы / оценка 2 за любой семестр -> 1%;
  2. неудовлетворительный результат текущей сессии  -> 1%;
  3. нет данных о сессии                            -> '???';
  4. наличие дисциплинарного взыскания              -> 1%;
  5. должность кроме «курсант»/«слушатель»          -> 25% (причина — приказ);
  6. шкала среднего результата: 3->5%, 4->15%, 5->25%.
"""

# ---------- Справочники формулы ----------

#: Результат сессии по минимальной оценке (оценки хранятся как строки).
SESSION_RESULT_BY_GRADE = {
    "2": "неудовлетворительно",
    "3": "удовлетворительно",
    "4": "хорошо",
    "5": "отлично",
}

#: Размер премии (%) по результату сессии (для обычных курсантов).
PREMIA_BY_SESSION_RESULT = {
    "неудовлетворительно": 1,
    "удовлетворительно": 5,
    "хорошо": 15,
    "отлично": 25,
}

#: Должности, дающие надбавку за должностное положение.
LEADER_POSITIONS = (
    "Заместитель командира взвода",
    "Командир 1 отделения",
    "Командир 2 отделения",
    "Командир 3 отделения",
)

#: Формы должностей для текста причины («Заместитель...» -> «заместителя...»).
POSITION_GENITIVES = {
    "Заместитель командира взвода": "заместителя командира взвода",
    "Командир 1 отделения": "командира 1 отделения",
    "Командир 2 отделения": "командира 2 отделения",
    "Командир 3 отделения": "командира 3 отделения",
}

NO_DATA = "нет данных"


def format_position_genitive(position):
    """Родительный падеж должности или None (как в прежнем UI-коде)."""
    if position in POSITION_GENITIVES:
        return POSITION_GENITIVES[position]
    return None


def compute_premia(min_grade, has_penalties, last_position, has_failed_subjects,
                   has_session_results=True):
    """Возвращает ``(размер_премии, причина, результат_сессии)``.

    Аргументы:
      min_grade           — минимальная оценка текущей сессии (str|None);
      has_penalties       — bool: есть взыскания за период;
      last_position       — кортеж (должность, дата ГГГГ-ММ-ДД, № приказа)
                            либо None;
      has_failed_subjects — bool: есть предмет без оценки/с оценкой 2
                            по любой сессии;
      has_session_results — bool: по выбранному семестру есть хоть какие-то
                            результаты (иначе min_grade доверять нельзя).
    """
    # 1. Несданные предметы имеют наивысший приоритет во всех случаях.
    if has_failed_subjects:
        return (1,
                "Не допущен, отсутствовал или оценка 2 по одному из предметов",
                "неудовлетворительно")

    # Результат сессии по минимальной оценке.
    session_result = SESSION_RESULT_BY_GRADE.get(
        min_grade, NO_DATA if not has_session_results else "")

    # 2. Провал текущей сессии.
    if min_grade == "2":
        return (1, "Неудовлетворительный результат сессии", "неудовлетворительно")

    # 3. Нет данных о сессии выбранного семестра.
    if not has_session_results or session_result == NO_DATA or min_grade is None:
        return ("???", "Нет данных о сессии", NO_DATA)

    # 4. Дисциплинарное взыскание.
    if has_penalties:
        return (1, "Наличие дисциплинарного взыскания", session_result)

    # 5. Надбавка за должность (кроме курсанта/слушателя).
    position = last_position[0] if last_position else None
    if position and position.lower() not in ("курсант", "слушатель"):
        formated = format_position_genitive(position) or position.lower()
        reason = (f"Занимает должность {formated} "
                  f"(приказ НВМедА № {last_position[2]} от "
                  f"{last_position[1]}г.)")
        return (25, reason, session_result)

    # 6. Шкала по результату сессии.
    size = PREMIA_BY_SESSION_RESULT.get(session_result, 0)
    return (size, "", session_result)
